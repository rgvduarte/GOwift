/**
 * Fills a mark scaled to `height`, its top-left corner at (x, y). Returns
 * its width. Does nothing where the canvas has no Path2D (tests).
 */
export function fillMark(ctx, path, box, { x, y, height, color = "#ffffff", Path = globalThis.Path2D }) {
  const scale = height / box.h;
  if (typeof Path === "function") {
    ctx.save();
    ctx.translate(x - box.x * scale, y - box.y * scale);
    ctx.scale(scale, scale);
    ctx.fillStyle = color;
    ctx.fill(new Path(path), "evenodd");
    ctx.restore();
  }
  return box.w * scale;
}
